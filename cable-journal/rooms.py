def pip(p, poly):
    x, y = p; inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]; x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            xin = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < xin: inside = not inside
    return inside


def room_of(p):
    for name, poly in ROOMS:
        if pip(p, poly): return name
    return '?'


