def rooms_display(internal):
    """'Пом. 1','Пом. 3' -> 'Кабинеты 1013, 1015'; 'Пом. 7','Коридор' -> 'Кабинет 1027, коридор'."""
    names = []
    for r in internal:
        n = ROOM_NAMES.get(r, r)
        if n not in names:
            names.append(n)
    cab = sorted(n.split()[1] for n in names if n.startswith('Кабинет '))
    wc = sorted(n.split()[1] for n in names if n.startswith('С/у '))
    other = [n for n in names if not n.startswith(('Кабинет ', 'С/у '))]
    parts = []
    if cab:
        parts.append(('Кабинет ' if len(cab) == 1 else 'Кабинеты ') + ', '.join(cab))
    if wc:
        parts.append('С/у ' + ', '.join(wc))
    parts += other
    out = parts[0]
    for p in parts[1:]:
        out += ', ' + (p if p.startswith('С/у') else p[0].lower() + p[1:])
    return out
